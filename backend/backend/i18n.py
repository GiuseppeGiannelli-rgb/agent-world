"""Spec 06: the backend's own texts -- run messages, speech bubbles, task
errors, Brain titles -- in every supported language. Agents write in the
run's language because prompts.language_rule() tells them to; these tables
cover what run.py writes itself.

N13: the HTTP errors (HTTP_ERRORS) speak the language of the app, ui.language,
not the run's: the UI shows them in a toast next to its own texts, and a run
keeps the language it started with while the UI may have changed since.

English comes first and is the default: a run without a language writes
its messages in English, and every table has exactly the English keys and
placeholders (test_i18n.py). The order of LANGUAGES is the order of the
selectors in the UI (public/js/i18n.js, LANGS)."""

LANGUAGES = {"en": "English", "it": "Italian", "es": "Spanish", "fr": "French", "de": "German"}
DEFAULT = "en"


def check(lang: str | None) -> str | None:
    """None means "not chosen" (the legacy rules); anything else must be supported."""
    if lang is None or (isinstance(lang, str) and lang in LANGUAGES):
        return lang
    raise ValueError(f"Unsupported language: {lang!r}")


