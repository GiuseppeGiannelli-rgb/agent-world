def tr(lang: str | None, key: str, **vars) -> str:
    return MESSAGES[check(lang) or DEFAULT][key].format(**vars)


def ui_language(cfg: dict) -> str:
    """N13: the language of the HTTP errors, the one chosen for the whole app.
    English when it is missing or unknown (a hand-edited local.json): an
    error must never turn into a 500 of its own."""
    lang = (cfg.get("ui") or {}).get("language")
    return lang if isinstance(lang, str) and lang in LANGUAGES else DEFAULT


def http_error(lang, key: str, **vars) -> str:
    table = HTTP_ERRORS[lang] if isinstance(lang, str) and lang in HTTP_ERRORS else HTTP_ERRORS[DEFAULT]
    return table[key].format(**vars)


class Refusal(ValueError):
    """A refusal raised below the routes (attachments, the Skill Hub): a key of
    HTTP_ERRORS and its values, which the route writes in the language of the
    app. Its own text is the English one, for logs and tracebacks."""

    def __init__(self, key: str, **vars):
        self.key, self.vars = key, vars
        super().__init__(http_error(DEFAULT, key, **vars))


def team_label(cfg: dict, team: str, lang: str | None) -> str:
    translated = TEAM_LABELS.get(check(lang) or DEFAULT, {}).get(team)
    return translated or (cfg["teams"].get(team) or {}).get("label") or team
